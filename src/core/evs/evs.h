#ifndef FF_EVS_H
#define FF_EVS_H

#include "common/ff_types.h"
#include "fsw_config.h"

typedef enum {
    FF_EVS_INFO = 1,
    FF_EVS_WARNING = 2,
    FF_EVS_ERROR = 3,
    FF_EVS_CRITICAL = 4
} FF_EvsType_t;

typedef struct
{
    uint16_t event_id;
    uint8_t type;
    uint8_t reserved;
    uint16_t app_id;
    uint64_t time_ns;
    char text[FF_EVS_TEXT_LEN];
} FF_EvsEvent_t;

typedef void (*FF_EvsListener_t)(const FF_EvsEvent_t *event);

typedef struct
{
    /* Cumulative deferred notifications accepted, delivered, and dropped at queue full. */
    uint32_t queued;
    uint32_t dispatched;
    uint32_t dropped;
} FF_EvsNotifyStats_t;

FF_Status_t FF_EvsInit(void);
void FF_EvsSetListener(FF_EvsListener_t listener);
/* Logs and immediately invokes the current listener outside the EVS lock. A
 * listener may therefore delay the caller; use only for ordinary events whose
 * producer permits synchronous delivery. */
FF_Status_t FF_EvsSend(uint16_t event_id, FF_EvsType_t type, FF_AppId_t app, const char *fmt, ...)
    __attribute__((format(printf, 4, 5)));
/* Explicit deferred-delivery alternative: attempt the EVS lock once, then log
 * and enqueue for later dispatch. Returns FF_TIMEOUT without any log, queue, or
 * statistics mutation if the lock is busy. Returns FF_NO_RESOURCE if a
 * configured listener's bounded queue is full; in that case the event remains
 * in the circular log and dropped-notification statistics increment. Notify
 * statistics count deferred API notifications only. */
FF_Status_t FF_EvsSendDeferred(uint16_t event_id, FF_EvsType_t type, FF_AppId_t app,
                               const char *fmt, ...) __attribute__((format(printf, 4, 5)));
uint32_t FF_EvsGetLog(FF_EvsEvent_t *out, uint32_t max_events);
uint32_t FF_EvsGetTotalCount(void);
/* Dispatch up to the queue-size snapshot taken at entry, capped by max_events.
 * Callbacks run outside the EVS lock. Recursive dispatcher calls return zero;
 * deferred events generated by callbacks are left for a later dispatch. */
uint32_t FF_EvsDispatchPending(uint32_t max_events);
FF_Status_t FF_EvsGetNotifyStats(FF_EvsNotifyStats_t *stats);

#ifdef FF_TEST_HOOKS
/* Deterministic contention injection for unit tests; absent from production builds. */
FF_Status_t FF_EvsTestLock(void);
FF_Status_t FF_EvsTestUnlock(void);
#endif

#endif /* FF_EVS_H */
